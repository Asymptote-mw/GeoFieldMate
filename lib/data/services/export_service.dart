import 'dart:io';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:path_provider/path_provider.dart';
import 'package:csv/csv.dart';
import 'package:share_plus/share_plus.dart';
import 'package:intl/intl.dart';
import '../models/field_record.dart';
import '../models/project.dart';

/// Service for exporting data to various formats
class ExportService {
  /// Export project to PDF report
  static Future<File> exportProjectToPDF(
    Project project,
    List<FieldRecord> records,
  ) async {
    final pdf = pw.Document();
    final dateFormat = DateFormat('MMM d, yyyy HH:mm');

    // Add pages
    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) {
          return [
            // Title
            pw.Header(
              level: 0,
              child: pw.Text(
                project.name,
                style: pw.TextStyle(
                  fontSize: 24,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ),
            pw.SizedBox(height: 20),

            // Project Info
            pw.Container(
              padding: const pw.EdgeInsets.all(12),
              decoration: pw.BoxDecoration(
                border: pw.Border.all(color: PdfColors.grey300),
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
              ),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  _buildPDFInfoRow(
                      'Location', project.location ?? 'Not specified'),
                  pw.SizedBox(height: 8),
                  _buildPDFInfoRow(
                    'Start Date',
                    DateFormat('MMMM d, yyyy').format(project.startDate),
                  ),
                  if (project.description.isNotEmpty) ...[
                    pw.SizedBox(height: 8),
                    _buildPDFInfoRow('Description', project.description),
                  ],
                  pw.SizedBox(height: 8),
                  _buildPDFInfoRow('Total Records', records.length.toString()),
                ],
              ),
            ),
            pw.SizedBox(height: 30),

            // Records
            pw.Text(
              'Field Records',
              style: pw.TextStyle(
                fontSize: 18,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 15),

            // Build record cards
            ...records.map((record) => _buildRecordCard(record, dateFormat)),
          ];
        },
      ),
    );

    // Save to file
    final output = await getTemporaryDirectory();
    final file = File('${output.path}/${project.name}_report.pdf');
    await file.writeAsBytes(await pdf.save());

    return file;
  }

  /// Export records to CSV
  static Future<File> exportRecordsToCSV(
    List<FieldRecord> records,
    String fileName,
  ) async {
    final List<List<dynamic>> rows = [];

    // Header row
    rows.add([
      'Timestamp',
      'Rock Type',
      'Specific Rock',
      'Dip (°)',
      'Strike (°)',
      'Latitude',
      'Longitude',
      'Elevation (m)',
      'Location Name',
      'Structural Features',
      'Notes',
      'Image Count',
    ]);

    // Data rows
    for (final record in records) {
      rows.add([
        DateFormat('yyyy-MM-dd HH:mm:ss').format(record.timestamp),
        record.rockType,
        record.specificRockName ?? '',
        record.dip ?? '',
        record.strike ?? '',
        record.latitude ?? '',
        record.longitude ?? '',
        record.elevation ?? '',
        record.locationName ?? '',
        record.structuralFeatures.join('; '),
        record.notes,
        record.imageUrls.length,
      ]);
    }

    // Convert to CSV
    final csv = const ListToCsvConverter().convert(rows);

    // Save to file
    final output = await getTemporaryDirectory();
    final file = File('${output.path}/$fileName.csv');
    await file.writeAsString(csv);

    return file;
  }

  /// Share PDF file
  static Future<void> sharePDF(File pdfFile) async {
    await Share.shareXFiles(
      [XFile(pdfFile.path)],
      subject: 'GeoFieldMate Field Report',
      text: 'Field data report generated by GeoFieldMate',
    );
  }

  /// Share CSV file
  static Future<void> shareCSV(File csvFile) async {
    await Share.shareXFiles(
      [XFile(csvFile.path)],
      subject: 'GeoFieldMate Field Data',
      text: 'Field data exported by GeoFieldMate',
    );
  }

  /// Print PDF
  static Future<void> printPDF(File pdfFile) async {
    final bytes = await pdfFile.readAsBytes();
    await Printing.layoutPdf(onLayout: (PdfPageFormat format) async => bytes);
  }

  // Helper methods for PDF generation
  static pw.Widget _buildPDFInfoRow(String label, String value) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.SizedBox(
          width: 120,
          child: pw.Text(
            label,
            style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
          ),
        ),
        pw.Expanded(
          child: pw.Text(value),
        ),
      ],
    );
  }

  static pw.Widget _buildRecordCard(FieldRecord record, DateFormat dateFormat) {
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 16),
      padding: const pw.EdgeInsets.all(12),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey300),
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          // Header
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Container(
                padding:
                    const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                decoration: pw.BoxDecoration(
                  color: _getRockTypeColor(record.rockType),
                  borderRadius:
                      const pw.BorderRadius.all(pw.Radius.circular(4)),
                ),
                child: pw.Text(
                  record.rockType.toUpperCase(),
                  style: const pw.TextStyle(
                    color: PdfColors.white,
                    fontSize: 10,
                  ),
                ),
              ),
              pw.Text(
                dateFormat.format(record.timestamp),
                style: const pw.TextStyle(
                  fontSize: 10,
                  color: PdfColors.grey700,
                ),
              ),
            ],
          ),
          pw.SizedBox(height: 12),

          // Rock name
          if (record.specificRockName != null) ...[
            pw.Text(
              record.specificRockName!,
              style: pw.TextStyle(
                fontSize: 14,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 8),
          ],

          // Measurements
          if (record.dip != null || record.strike != null) ...[
            pw.Text(
              'Dip: ${record.dip ?? 'N/A'}° | Strike: ${record.strike ?? 'N/A'}°',
              style: const pw.TextStyle(fontSize: 12),
            ),
            pw.SizedBox(height: 6),
          ],

          // Location
          if (record.locationName != null ||
              (record.latitude != null && record.longitude != null)) ...[
            pw.Text(
              'Location: ${record.locationName ?? '${record.latitude!.toStringAsFixed(6)}, ${record.longitude!.toStringAsFixed(6)}'}',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            ),
            pw.SizedBox(height: 6),
          ],

          // Structural features
          if (record.structuralFeatures.isNotEmpty) ...[
            pw.Text(
              'Structures: ${record.structuralFeatures.join(', ')}',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            ),
            pw.SizedBox(height: 6),
          ],

          // Notes
          if (record.notes.isNotEmpty) ...[
            pw.Text(
              'Notes: ${record.notes}',
              style: const pw.TextStyle(fontSize: 10),
            ),
          ],

          // Images
          if (record.imageUrls.isNotEmpty) ...[
            pw.SizedBox(height: 6),
            pw.Text(
              'Photos: ${record.imageUrls.length} attached',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            ),
          ],
        ],
      ),
    );
  }

  static PdfColor _getRockTypeColor(String rockType) {
    switch (rockType.toLowerCase()) {
      case 'igneous':
        return PdfColors.red700;
      case 'sedimentary':
        return PdfColors.orange700;
      case 'metamorphic':
        return PdfColors.purple700;
      default:
        return PdfColors.grey;
    }
  }
}
